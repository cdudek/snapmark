import assert from 'assert';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';

// Source checks of the calm style (change 2026-10-27-calm-style): the tokens and how each window reads them.
const app = path.join(__dirname, '../..');
const read = (file: string) => fs.readFileSync(path.join(app, file), 'utf8');
const tokens = read('src/tokens.css');
const lock = JSON.parse(read('design/tokens.lock.json')) as { repo: string; commit: string; sha256: string };

// @F1 @2026-10-27-calm-style tokens.css is design-system-starter at 3048d42 with Snapmark's accent; its first line names it
assert.deepStrictEqual([lock.repo, lock.commit], ['https://github.com/cdudek/design-system-starter', '3048d42'], '@F1 the pinned build');
assert.ok(tokens.split('\n')[0].includes(`${lock.repo} at ${lock.commit}`), '@F1 the first line names the repo and commit');
assert.ok(tokens.includes('/* Generated by scripts/build-tokens.mjs. Do not edit. */'), '@F1 the starter build output');
assert.ok(tokens.includes('  --ds-color-accent: #0f72db;') && tokens.includes('  --ds-color-on-accent: #ffffff;'), '@F1 the accent');
assert.ok(tokens.includes(':root[data-surface="system"] {'), '@F1 the system surfaces');

// @F2 @2026-10-27-calm-style a tokens.css edited by hand, or built from another commit, fails against the lock
assert.strictEqual(crypto.createHash('sha256').update(tokens).digest('hex'), lock.sha256, '@F2 tokens.css matches tokens.lock.json');

// @F3 @2026-10-27-calm-style every window loads tokens.css, then surface.js, in its <head> before its own styles;
// surface.js sets data-surface="system" on the root on macOS only
const windows = fs.readdirSync(path.join(app, 'src')).filter((f) => f.endsWith('.html'));
assert.deepStrictEqual(
  windows,
  [
    'area.html',
    'bar.html',
    'countdown.html',
    'editor.html',
    'recorder.html',
    'scroll.html',
    'settings.html',
    'shortcuts.html',
    'viewer.html',
  ],
  '@F3 every window',
);
for (const w of windows) {
  const head = read(`src/${w}`).split('</head>')[0];
  const [link, script, style] = ['<link rel="stylesheet" href="tokens.css" />', '<script src="surface.js"></script>', '<style>'].map((s) =>
    head.indexOf(s),
  );
  assert.ok(link > 0 && script > link && (style < 0 || style > script), `@F3 ${w} loads tokens.css and surface.js first`);
  assert.ok(head.includes("default-src 'self';"), `@F3 ${w} keeps its CSP`);
}
assert.ok(
  read('src/surface.ts').includes("if (/Mac/.test(navigator.platform)) document.documentElement.dataset.surface = 'system';"),
  '@F3 data-surface="system" on macOS only',
);

// @F15 @2026-10-27-calm-style bar.html has no colour literal: no hex, no colour function, no named or system colour.
// Its colours are --ds-* tokens (and currentColor, which inherits one)
const colourLiterals = (html: string) =>
  html.match(
    /#[0-9a-f]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color|light-dark|color-mix)\(|(?<![-\w])(?:white|black|transparent|red|green|blue|gr[ae]y|canvas|canvastext|graytext|accentcolor|highlight)(?![-\w])/gi,
  ) ?? [];
const bar = read('src/bar.html');
assert.deepStrictEqual(colourLiterals(bar), [], '@F15 bar.html uses no colour literal');
assert.ok((bar.match(/var\(--ds-color-[a-z-]+\)/g) ?? []).length >= 6, '@F15 its colours come from the tokens');
assert.ok(!/var\(--(?!ds-)/.test(bar), '@F15 no other variables');

// @N1 @2026-10-27-calm-style "To" is in the bar's text colour: the system's GrayText is #808080, under 4.5:1. The ring
// is not -webkit-focus-ring-color, which Chromium draws in its own orange: bar.ts sets it (test/capture.test.ts barRing)
assert.ok(!/#dest-to\s*\{/.test(bar), '@N1 no colour of its own for "To"');
const barTs = read('src/bar.ts');
assert.ok(barTs.includes("style.setProperty('--ds-color-focus', s.ring ?? 'var(--ds-color-ink)')"), '@N1 @F10 the ring colour');

// @F10 @2026-10-27-calm-style a digit or a click chooses without the ring; only an arrow asks for it
assert.ok(barTs.includes('const choose = (m: CaptureMode, ring = false) =>'), '@F10 no ring by default');
assert.strictEqual((barTs.match(/as CaptureMode, true\)/g) ?? []).length, 1, '@F10 the arrows alone ring');

// @N1 @F10 @2026-10-27-calm-style the panels ring as the bar does: main passes the ring, scroll.ts sets it
assert.ok(
  read('src/scroll.ts').includes("style.setProperty('--ds-color-focus', query.get('ring') || 'var(--ds-color-ink)')"),
  "@N1 @F10 the panels' ring colour",
);

// @A5 @2026-10-27-calm-style Options stays beside the destination; the spare room falls before Capture
assert.ok(/#options \{\s+margin-right: auto;\s+\}/.test(bar) && !bar.includes('margin-left: auto'), '@A5 Capture alone at the right');

// @F21 @2026-10-27-calm-style Record joins the one row as the sixth mode, its key in its drawn tooltip like the others
assert.deepStrictEqual(
  [...bar.matchAll(/data-mode="(\w+)"[^>]*?data-tip="([^"]+)"\s+data-key="([^"]+)"/g)].map((m) => `${m[1]} ${m[2]} ${m[3]}`).slice(-2),
  ['scroll Scrolling 5', 'record Record 6'],
  '@F21 Record is the sixth mode',
);

// @F22 @2026-10-27-calm-style the panels' .html files have no colour literal either; their colours are --ds-* tokens.
// The recorder is never shown and has no colours
for (const panel of ['countdown.html', 'area.html', 'scroll.html', 'recorder.html']) {
  const html = read(`src/${panel}`);
  assert.deepStrictEqual(colourLiterals(html), [], `@F22 ${panel} uses no colour literal`);
  assert.ok(panel === 'recorder.html' || /var\(--ds-color-[a-z-]+\)/.test(html), `@F22 ${panel} takes its colours from the tokens`);
}

// @F20 @2026-10-27-calm-style Record's recording control, in scroll.html, is in the calm style: Done the one accent
// fill, ⓧ the plain icon the scrolling control's Esc is, the recording dot and the warning from the tokens
const scroll = read('src/scroll.html');
assert.ok(
  /#done,\s+#rec-done \{\s+background: var\(--ds-button-fill-primary\);/.test(scroll),
  '@F20 Done fills with the accent, in both controls',
);
assert.deepStrictEqual(
  [...scroll.matchAll(/<button id="([\w-]+)" class="(?:scroll|rec) x"/g)].map((m) => m[1]),
  ['cancel', 'rec-cancel'],
  '@F20 both cancels are the plain icon',
);
assert.ok(scroll.includes('background: var(--ds-color-error);') && !scroll.includes('--rec-dot'), '@F20 the recording dot from the tokens');

// @F31 @2026-10-27-calm-style the annotation colours and marks are exactly as in v0.24.0: the palette, the card's colour,
// Remove's and Highlight's (tools.ts), and every line that draws a mark (editor.ts's shapes section, hashed at v0.24.0)
const editorTs = read('src/editor.ts');
const shapes = editorTs.slice(editorTs.indexOf('// ---------- shapes ----------'), editorTs.indexOf('// ---------- tools ----------'));
assert.strictEqual(
  crypto.createHash('sha256').update(shapes).digest('hex'),
  'ad24df6b4d87eacf42d1c431da2c0577036a0b8fe44b9f575d62406c2ca03bcb',
  '@F31 the marks are drawn as in v0.24.0',
);
const palette: [string, string][] = [
  ['Coral red', 'RED'],
  ['Orange', "'#f76b15'"],
  ['Amber', "'#ffb224'"],
  ['Green', "'#30a46c'"],
  ['Teal', "'#12a594'"],
  ['Cyan', "'#05a2c2'"],
  ['Blue', "'#2492ff'"],
  ['Violet', "'#8b3dff'"],
  ['Pink', "'#ef28a7'"],
  ['Graphite', "'#2c2c31'"],
];
assert.ok(
  editorTs.includes(`const PALETTE: [string, string][] = [\n${palette.map(([n, c]) => `  ['${n}', ${c}],\n`).join('')}];`),
  '@F31 the palette',
);
assert.ok(editorTs.includes("const CARD_BG = '#fef9c3';"), "@F31 the card's colour");
const toolsTs = read('src/tools.ts');
assert.ok(toolsTs.includes("const RED = '#e5484d';") && toolsTs.includes("const YELLOW = '#facc15';"), "@F31 Remove's and Highlight's");

// @F26 @2026-10-27-calm-style every tool stays reachable by key, wherever its button is: the keys pick a group from
// GROUPS, never from the toolbar's buttons, some of which More holds
assert.ok(
  editorTs.includes('const numbered = e.metaKey && /^\\d$/.test(e.key) ? GROUPS.findIndex((x) => x.key === e.key) : -1;') &&
    editorTs.includes('const g = GROUPS.findIndex((x) => x.key === e.key.toLowerCase());'),
  '@F26 the keys',
);
assert.ok(editorTs.includes('b.hidden = i >= GROUPS.length - overflow;'), '@F26 More holds the last tools');

// @F25 @N1 @2026-10-27-calm-style the editor's ring is set from main's accent (surface.ts), never Chromium's orange; its
// text that must be read is in the text colour, never the system's dim text, which misses 4.5:1 (questions.md)
assert.ok(
  read('src/surface.ts').includes(
    "document.documentElement.style.setProperty('--ds-color-focus', new URLSearchParams(location.search).get('ring') || 'var(--ds-color-ink)');",
  ),
  '@F25 @N1 every window takes its ring from main',
);
const editorHtml = read('src/editor.html');
assert.ok(!/--ds-color-(?:dim|faint)\b/.test(editorHtml), '@N1 the editor has no dim text');
assert.ok(
  read('src/main.ts').includes("loadFile(path.join(__dirname, 'editor.html'), { query: { ring: focusRing() ?? '' } })"),
  '@F25 the editor gets its ring',
);
// @2026-10-27-calm-style no captions: the editor's keys are in drawn tooltips, as the bar's (owner, milestone 1 finding 4)
assert.ok(!/class="(?:cap|group)"/.test(editorHtml) && !editorTs.includes("'cap'"), 'no key captions under the tools');

console.log('style: ok');
