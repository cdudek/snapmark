import { contextBridge, ipcRenderer, webFrame } from 'electron';

const api: Window['snapmark'] = {
  init: () => ipcRenderer.invoke('editor:init'),
  frame: (i) => ipcRenderer.invoke('editor:frame', i),
  save: (data) => ipcRenderer.invoke('editor:save', data),
  copyImage: (png) => ipcRenderer.invoke('editor:copy', png),
  saveImageAs: (png) => ipcRenderer.invoke('editor:saveAs', png),
  beautify: (settings) => ipcRenderer.send('editor:beautify', settings),
  secrets: () => ipcRenderer.invoke('editor:secrets'),
  dirty: (value) => ipcRenderer.send('editor:dirty', value),
  stash: (state, copied) => void ipcRenderer.sendSync('editor:stash', state, copied),
  destination: (oneShot) => ipcRenderer.invoke('editor:destination', oneShot),
  onMoveError: (cb) => void ipcRenderer.on('editor:move-error', (_e, session: string) => cb(session)),
  onSession: (cb) => void ipcRenderer.on('editor:session', (_e, session: string, count: number) => cb(session, count)),
  onSingleKeys: (cb) => void ipcRenderer.on('editor:single-keys', (_e, on: boolean) => cb(on)),
  color: (c) => ipcRenderer.send('editor:color', c),
  customColors: (list) => ipcRenderer.send('editor:custom-colors', list),
  sessionsMenu: (at) => ipcRenderer.send('editor:sessions-menu', at),
  shareMenu: (at) => ipcRenderer.send('editor:share-menu', at),
  onShare: (cb) => void ipcRenderer.on('editor:share', (_e, what: 'copy' | 'saveAs') => cb(what)),
  viewerInit: () => ipcRenderer.invoke('viewer:init'),
  viewerSave: (from, md) => ipcRenderer.invoke('viewer:save', from, md),
  viewerExternal: () => ipcRenderer.send('viewer:external'),
  viewerRemove: (n) => ipcRenderer.invoke('viewer:remove', n),
  viewerEdit: (n) => ipcRenderer.send('viewer:edit', n),
  viewerRename: (name) => ipcRenderer.invoke('viewer:rename', name),
  viewerReopen: (dir) => ipcRenderer.invoke('viewer:reopen', dir),
  onViewerReload: (cb) => void ipcRenderer.on('viewer:reload', (_e, data: ViewerInit) => cb(data)),
  clearImageCache: () => webFrame.clearCache(),
  areaDone: (area) => ipcRenderer.send('area:done', area),
  scrollDone: (ok) => ipcRenderer.send('scroll:done', ok),
  shortcutsInit: () => ipcRenderer.invoke('shortcuts:init'),
  settingsInit: () => ipcRenderer.invoke('settings:init'),
  settingsSet: (key, value) => ipcRenderer.invoke('settings:set', key, value),
  settingsRun: (what) => ipcRenderer.invoke('settings:run', what),
  barInit: () => ipcRenderer.invoke('bar:init'),
  barCapture: (mode) => ipcRenderer.send('bar:capture', mode),
  barOptions: (mode, at) => ipcRenderer.send('bar:options', mode, at),
  barClose: () => ipcRenderer.send('bar:close'),
  barOneShot: (on) => ipcRenderer.send('bar:one-shot', on),
  barSessions: (at) => ipcRenderer.send('bar:sessions', at),
  onBarState: (cb) => void ipcRenderer.on('bar:state', (_e, s: BarInit) => cb(s)),
  onScrollStatus: (cb) => void ipcRenderer.on('scroll:status', (_e, status: ScrollStatus) => cb(status)),
  onRecordStatus: (cb) => void ipcRenderer.on('record:status', (_e, status: RecordStatus) => cb(status)),
  recorderFrame: (t, png, thumb) => ipcRenderer.send('recorder:frame', t, png, thumb),
  recorderFailed: (reason) => ipcRenderer.send('recorder:failed', reason),
  onCountdown: (cb) => void ipcRenderer.on('countdown:digit', (_e, s: number) => cb(s)),
};

contextBridge.exposeInMainWorld('snapmark', api);
